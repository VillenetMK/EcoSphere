-- One permanent EcoSphere installation with replaceable ESP32 controllers.
-- Existing telemetry and control targets remain attached to device_control id=1.

create table private.ecosystems (
  id smallint primary key default 1,
  name text not null default 'EcoSphere principal',
  active_controller_id bigint,
  legacy_writes_allowed boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ecosystems_singleton check (id = 1),
  constraint ecosystems_name_length check (char_length(name) between 3 and 80)
);

create table private.device_controllers (
  id bigint generated by default as identity primary key,
  ecosystem_id smallint not null default 1
    references private.ecosystems(id) on delete restrict,
  hardware_uid text not null,
  secret_hash bytea not null,
  pairing_code_hash bytea,
  pairing_expires_at timestamptz,
  status text not null default 'pending',
  firmware_version text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz,
  activated_at timestamptz,
  activated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint device_controllers_hardware_uid_format
    check (hardware_uid ~ '^[0-9A-F]{12}$'),
  constraint device_controllers_status
    check (status in ('pending', 'active', 'standby', 'revoked')),
  constraint device_controllers_firmware_length
    check (firmware_version is null or char_length(firmware_version) between 1 and 40),
  constraint device_controllers_pairing_state check (
    (pairing_code_hash is null and pairing_expires_at is null)
    or (pairing_code_hash is not null and pairing_expires_at is not null)
  )
);

create unique index device_controllers_hardware_uid_unique
  on private.device_controllers (hardware_uid);
create index device_controllers_ecosystem_id_idx
  on private.device_controllers (ecosystem_id);
create index device_controllers_pairing_code_hash_idx
  on private.device_controllers (pairing_code_hash)
  where pairing_code_hash is not null;
create unique index device_controllers_one_active_per_ecosystem
  on private.device_controllers (ecosystem_id)
  where status = 'active';

alter table private.ecosystems
  add constraint ecosystems_active_controller_fk
  foreign key (active_controller_id)
  references private.device_controllers(id)
  on delete set null;

create index ecosystems_active_controller_id_idx
  on private.ecosystems (active_controller_id)
  where active_controller_id is not null;

create table private.controller_events (
  id bigint generated by default as identity primary key,
  ecosystem_id smallint not null
    references private.ecosystems(id) on delete restrict,
  controller_id bigint
    references private.device_controllers(id) on delete set null,
  event_type text not null,
  actor_user_id uuid references auth.users(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint controller_events_type check (
    event_type in (
      'pairing_started',
      'controller_activated',
      'controller_replaced',
      'secure_mode_enabled'
    )
  ),
  constraint controller_events_details_object
    check (jsonb_typeof(details) = 'object')
);

create index controller_events_ecosystem_created_idx
  on private.controller_events (ecosystem_id, created_at desc);
create index controller_events_controller_id_idx
  on private.controller_events (controller_id)
  where controller_id is not null;

